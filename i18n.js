let currentLang = 'ar';
try { currentLang = localStorage.getItem('fla7in_lang') || 'ar'; } catch(e){}
let chosenLang = currentLang;

function t(key) {
    const dict = i18n[currentLang] || i18n['ar'];
    return dict[key] || key;
}

function tRaw(key, lang) {
    const dict = i18n[lang] || i18n['ar'];
    return dict[key] || key;
}

function tByArabic(arabicText) {
    if (!arabicText) return arabicText;
    if (currentLang === 'ar') return arabicText;
    
    // Find key in ar dictionary
    const arDict = i18n['ar'];
    let foundKey = null;
    const normalizedTarget = String(arabicText).trim();
    for (const key in arDict) {
        if (typeof arDict[key] === 'string' && arDict[key].trim() === normalizedTarget) {
            foundKey = key;
            break;
        }
    }
    
    const dict = i18n[currentLang] || i18n['ar'];
    if (foundKey && dict[foundKey]) {
        return dict[foundKey];
    }
    return arabicText;
}

function switchLang(lang) {
    currentLang = lang;
    try { localStorage.setItem('fla7in_lang', lang); } catch(e){}

    const txt = i18n[lang];
    const html = document.documentElement;
    html.lang = lang;
    html.dir = txt.dir;

    document.body.className = lang !== 'ar' ? 'lang-' + lang : '';

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (txt[key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = txt[key];
            } else {
                el.textContent = txt[key];
            }
        }
    });

    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (txt[key]) el.innerHTML = txt[key];
    });

    ['Ar','Fr','En'].forEach(l => {
        const nbBtn = document.getElementById('nb'+l);
        const lsBtn = document.getElementById('ls'+l);
        const active = l.toLowerCase() === lang;
        if(nbBtn) nbBtn.classList.toggle('active', active);
        if(lsBtn) lsBtn.classList.toggle('active', active);
    });

    const langSecGrid = document.querySelector('.lang-section-grid');
    if (langSecGrid) langSecGrid.style.direction = txt.dir;
    
    document.dispatchEvent(new CustomEvent('langChanged', { detail: { lang } }));
}

document.addEventListener('DOMContentLoaded', () => {
    switchLang(currentLang);
});
